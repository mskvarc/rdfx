use rdf_term::{BlankIdBuf, LocalTerm, Quad, dataset::HashDataset, iri};

fn test(a: HashDataset, b: HashDataset) {
    if rdf_term::dataset::isomorphism::find_hash_bijection(&a, &b).is_some() {
        panic!("bijection found!")
    }
}
